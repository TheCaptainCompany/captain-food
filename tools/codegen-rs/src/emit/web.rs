/// Emit `crates/web/assets/tokens.generated.css` — the `design_tokens` DSL block as CSS custom
/// properties on `:root` (#115). Prefix per group: colors → `--color-*`, typography scale →
/// `--text-*` (+ `--font-family`), spacing → `--space-*`, radius → `--radius-*`, shadows →
/// `--shadow-*`, breakpoints → `--bp-*`. The DSL stays the palette source of truth; `app.css`
/// consumes only these variables.
pub(crate) fn emit_web_tokens_css(model: &Model) -> String {
    let tokens = model
        .defs
        .get("screens/restaurant_frontoffice.yaml")
        .and_then(|v| v.get("design_tokens"))
        .and_then(|v| v.as_mapping());

    let mut out = String::from(
        "/* GENERATED by the Captain.Food codegen from specs/screens/restaurant_frontoffice.yaml\n   (#/design_tokens, #115) — do not edit by hand. The design-token palette as CSS custom\n   properties; crates/web/assets/app.css consumes these via var(--…). */\n:root {\n",
    );
    // (group key, css prefix). Emit in a fixed order for byte-stability.
    let groups: [(&str, &str); 6] = [
        ("colors", "color"),
        ("typography", "text"),
        ("spacing", "space"),
        ("radius", "radius"),
        ("shadows", "shadow"),
        ("breakpoints", "bp"),
    ];
    let kebab = |s: &str| s.replace('_', "-");
    for (group, prefix) in groups {
        let Some(g) = tokens.and_then(|t| t.get(group)).and_then(|v| v.as_mapping()) else { continue };
        out.push_str(&format!("  /* {group} */\n"));
        for (k, v) in g {
            let Some(key) = k.as_str() else { continue };
            // typography.scale is a nested map (xs/sm/base/…) → --text-xs etc.; font_family flat.
            if let Some(nested) = v.as_mapping() {
                for (nk, nv) in nested {
                    if let (Some(nkey), Some(val)) = (nk.as_str(), scalar_css(nv)) {
                        out.push_str(&format!("  --{prefix}-{}: {val};\n", kebab(nkey)));
                    }
                }
            } else if let Some(val) = scalar_css(v) {
                // typography.font_family → --font-family (special-cased out of the --text-* prefix).
                let name = if group == "typography" && key == "font_family" {
                    "font-family".to_string()
                } else {
                    format!("{prefix}-{}", kebab(key))
                };
                out.push_str(&format!("  --{name}: {val};\n"));
            }
        }
    }
    out.push_str("}\n");
    out
}

/// A YAML scalar as a CSS value string (strings verbatim, numbers stringified).
pub(crate) fn scalar_css(v: &Value) -> Option<String> {
    match v {
        Value::String(s) => Some(s.clone()),
        Value::Number(n) => Some(n.to_string()),
        _ => None,
    }
}

