/// Escape a spec string for embedding in a Rust string literal.
pub(crate) fn rust_string_lit(s: &str) -> String {
    s.replace('\\', "\\\\").replace('"', "\\\"").replace('\n', "\\n")
}

/// SCREAMING_SNAKE const name for a PascalCase errors.yaml key (`SlugAlreadyTaken` →
/// `SLUG_ALREADY_TAKEN`).
pub(crate) fn screaming_snake(name: &str) -> String {
    snake_field(name).trim_start_matches('_').to_ascii_uppercase()
}

/// Emit ONE anticipated-error `ErrorDef` const — the per-item body shared by the per-scope crate
/// emitter (`emit_domain_scope_crates`), which owns where each error now lives (#373).
pub(crate) fn push_error_const(out: &mut String, name: &str, node: &Value) {
    let konst = screaming_snake(name);
    let en = node
        .get("messages")
        .and_then(|ms| ms.get("en"))
        .and_then(|x| x.as_str())
        .unwrap_or("");
    let fr = node
        .get("messages")
        .and_then(|ms| ms.get("fr"))
        .and_then(|x| x.as_str())
        .unwrap_or("");
    out.push('\n');
    push_doc(out, "", node.get("description").and_then(|x| x.as_str()));
    // Document the typed context fields (camelCase keys of the rejection's JSON context).
    if let Some(ctx) = node.get("context").and_then(|c| c.as_mapping()) {
        if !ctx.is_empty() {
            let fields: Vec<&str> = ctx.iter().filter_map(|(ck, _)| ck.as_str()).collect();
            out.push_str(&format!("/// Context: `{}`.\n", fields.join("`, `")));
        }
    }
    out.push_str(&format!(
        "pub const {}: ErrorDef = ErrorDef {{\n    code: \"{}\",\n    message_en: \"{}\",\n    message_fr: \"{}\",\n}};\n",
        konst,
        rust_string_lit(name),
        rust_string_lit(en),
        rust_string_lit(fr)
    ));
}

/// Emit `crates/domain/src/generated/errors.rs` — since #373 the per-error `ErrorDef` consts live
/// in the per-scope crates (with `ErrorDef` + `interpolate` in the kernel, `domain-common`); this
/// facade re-exports them and keeps the genuinely GLOBAL pieces: the whole-catalog `ERRORS` slice,
/// `find` (wire-code lookup — a rejection's code arrives untyped off the wire, so the lookup must
/// span every scope), and the localized `message_en`/`message_fr` built on both. Error contract
/// P-10: the const's `code` is the errors.yaml key = the GraphQL `extensions.code`.
pub(crate) fn emit_domain_errors(model: &Model) -> String {
    let mut out = facade_reexports(
        model,
        "errors.yaml",
        "errors",
        "The per-error `ErrorDef` consts (kernel: also `ErrorDef` + `interpolate`)",
    );
    // The kernel's errors module exists whenever ANY scope declares errors (it owns `ErrorDef` +
    // `interpolate`), so re-export it even when the kernel declares no error items of its own —
    // the global catalog below is typed by it.
    let kernel_line = format!("pub use {}::errors::*;\n", domain_crate_ident(KERNEL_SCOPE));
    if !out.contains(&kernel_line)
        && model.scopes.iter().any(|s| !scope_items(model, s, "errors.yaml").is_empty())
    {
        out.push_str(&kernel_line);
    }
    let mut names: Vec<String> = Vec::new();
    if let Some(Value::Mapping(m)) = model.defs.get("errors.yaml") {
        for (k, _) in m {
            if let Some(name) = k.as_str() {
                names.push(screaming_snake(name));
            }
        }
    }
    out.push_str("\n/// Every anticipated error, in errors.yaml order.\npub const ERRORS: &[ErrorDef] = &[\n");
    for n in &names {
        out.push_str(&format!("    {},\n", n));
    }
    out.push_str("];\n");
    out.push_str(
        "\n/// Look up an anticipated error by its stable PascalCase code.\npub fn find(code: &str) -> Option<&'static ErrorDef> {\n    ERRORS.iter().find(|e| e.code == code)\n}\n\n/// The interpolated English message for `code`, if it is a catalogued error.\npub fn message_en(code: &str, context: &serde_json::Value) -> Option<String> {\n    find(code).map(|e| interpolate(e.message_en, context))\n}\n\n/// The interpolated French message for `code`, if it is a catalogued error.\npub fn message_fr(code: &str, context: &serde_json::Value) -> Option<String> {\n    find(code).map(|e| interpolate(e.message_fr, context))\n}\n",
    );
    out
}

// ─── crates/domain/src/generated/states.rs (declared-state folds, PROP-20260728-135632 §2.1) ──

/// Emit `crates/domain/src/generated/states.rs` — one module per actor declaring a `state:` block
/// in actors.yaml (#242 Runtime A): the declared, event-lineaged fold as plain data/match — the
/// SAME shape as the hand-written write-side state so parity is assertable field by field. Modes:
/// `latest` assigns the lineage property; `flag` sets on `from`, clears on `removedBy`; `set`
/// inserts/removes its element (scalar lineage property, or a composite read off the payload by
/// key name in declaration order); `count` increments. A BIRTH event (one appearing in the `from`
/// lineage of every non-nullable latest field) constructs the state fresh (replace semantics —
/// mirroring the hand folds); every other arm requires an existing state (`state?`), so a stream
/// that never births folds to `None`.
pub(crate) fn emit_domain_states(model: &Model) -> String {
    let mut out = String::from(
        "// GENERATED by the Captain.Food codegen from specs/actors.yaml `state` blocks\n// (PROP-20260728-135632 §2.1, #242 Runtime A) — do not edit by hand. Declared write-side state\n// folds as plain data/match (no SDK, no I/O — the domain stays dependency-free): the hand-written\n// aggregate keeps its own fold, and the parity test asserts the two can never disagree with the\n// declared spec lineage.\n",
    );
    let Some(Value::Mapping(actors)) = model.defs.get("actors.yaml") else { return out };
    for (k, def) in actors {
        let actor = match k.as_str() {
            Some(s) if s != "principals" => s,
            _ => continue,
        };
        let Some(Value::Mapping(state)) = def.get("state") else { continue };
        // #582 (PROP-20260815-142349 §19): an actor with a `lifecycle:` block keeps its
        // HAND-WRITTEN fold — the declared-state grammar cannot yet express the
        // lifecycle-owned `status` (`st-status-duplicated` forbids redeclaring it), nested
        // payload lineage (`checkout/orderId`) or entity-typed fields, so a generated fold
        // here would be a second, partial state type for the same actor. Its `state:` block
        // is DECLARATION-ONLY this slice: it types the actor's `answers:` replies, and
        // YAML↔fold parity is enforced by the reply-construction tests colocated in the hand
        // fold modules (compiler-checked), not by this emitter. Fold generation composes with
        // the lifecycle table in the states-generation slice 2 (#242).
        if def.get("lifecycle").is_some() {
            continue;
        }

        // Parse the fields in declaration order.
        struct Field {
            name: String,             // spec (camelCase) name
            rust: String,             // snake_case field
            mode: String,             // latest | flag | set | count
            ty: String,               // rendered Rust type
            nullable: bool,
            scalar_of: Option<String>,          // set: scalar element type
            composite_of: Vec<(String, String)>, // set: composite (payload key, element type)
            from: Vec<(String, Option<String>)>,     // (event, Some(prop) | None)
            removed_by: Vec<(String, Option<String>)>,
        }
        let scalar_name = |node: &Value| -> Option<String> {
            node.get("$ref").and_then(|r| r.as_str()).and_then(ref_name)
        };
        let lineage = |node: Option<&Value>| -> Vec<(String, Option<String>)> {
            node.and_then(|v| v.as_sequence())
                .map(|seq| {
                    seq.iter()
                        .filter_map(|e| e.get("$ref").and_then(|r| r.as_str()))
                        .filter_map(|r| lineage_parts(r).map(|(ev, p)| (ev.to_string(), p.map(str::to_string))))
                        .collect()
                })
                .unwrap_or_default()
        };
        let mut fields: Vec<Field> = Vec::new();
        let mut scalar_imports: BTreeSet<String> = BTreeSet::new();
        for (fk, fdef) in state {
            let Some(name) = fk.as_str() else { continue };
            let mode = fdef
                .get("mode")
                .and_then(|m| m.as_str())
                .unwrap_or("latest")
                .to_string();
            let nullable = fdef.get("nullable").and_then(|n| n.as_bool()).unwrap_or(false);
            let mut scalar_of = None;
            let mut composite_of = Vec::new();
            let ty = match mode.as_str() {
                "flag" => "bool".to_string(),
                "count" => "i64".to_string(),
                "set" => match fdef.get("of") {
                    Some(of) if of.get("$ref").is_some() => {
                        let n = scalar_name(of).expect("set `of` $ref must name a scalar");
                        scalar_imports.insert(n.clone());
                        scalar_of = Some(n.clone());
                        format!("Vec<{}>", n)
                    }
                    Some(Value::Mapping(keys)) => {
                        let mut parts = Vec::new();
                        for (kk, kv) in keys {
                            let key = kk.as_str().expect("composite `of` key").to_string();
                            let n = scalar_name(kv).expect("composite `of` value must be a scalar $ref");
                            scalar_imports.insert(n.clone());
                            parts.push(n.clone());
                            composite_of.push((key, n));
                        }
                        format!("Vec<({})>", parts.join(", "))
                    }
                    _ => panic!("actors.yaml {}/state/{}: set without `of`", actor, name),
                },
                _ => {
                    // latest: `type` is a scalar $ref or an inline boolean.
                    let base = match fdef.get("type") {
                        Some(t) if t.get("$ref").is_some() => {
                            let n = scalar_name(t).expect("state `type` $ref must name a scalar");
                            scalar_imports.insert(n.clone());
                            n
                        }
                        Some(t) if t.as_str() == Some("boolean") => "bool".to_string(),
                        other => panic!(
                            "actors.yaml {}/state/{}: unsupported latest type {:?} — extend emit_domain_states",
                            actor, name, other
                        ),
                    };
                    if nullable { format!("Option<{}>", base) } else { base }
                }
            };
            fields.push(Field {
                name: name.to_string(),
                rust: snake_field(name),
                mode,
                ty,
                nullable,
                scalar_of,
                composite_of,
                from: lineage(fdef.get("from")),
                removed_by: lineage(fdef.get("removedBy")),
            });
        }

        // Birth events: appear in the `from` lineage of EVERY non-nullable latest field (those are
        // the fields with no meaningful default — a state cannot exist without them).
        let strict: Vec<&Field> = fields
            .iter()
            .filter(|f| f.mode == "latest" && !f.nullable)
            .collect();
        let mut birth_events: Vec<String> = Vec::new();
        if let Some(first) = strict.first() {
            for (ev, _) in &first.from {
                if strict.iter().all(|f| f.from.iter().any(|(e, _)| e == ev)) {
                    birth_events.push(ev.clone());
                }
            }
        }
        assert!(
            strict.is_empty() || !birth_events.is_empty(),
            "actors.yaml {}/state: no single event assigns every non-nullable latest field — no birth arm can be generated",
            actor
        );

        // Group the per-event mutation statements (insertion order = spec field order).
        #[allow(clippy::type_complexity)]
        let mut arms: Vec<(String, Vec<String>)> = Vec::new();
        let stmt = |ev: &str, s: String, arms: &mut Vec<(String, Vec<String>)>| {
            match arms.iter_mut().find(|(e, _)| e == ev) {
                Some((_, v)) => v.push(s),
                None => arms.push((ev.to_string(), vec![s])),
            }
        };
        for f in &fields {
            match f.mode.as_str() {
                "latest" => {
                    for (ev, prop) in &f.from {
                        let p = prop.as_deref().unwrap_or_else(|| panic!(
                            "actors.yaml {}/state/{}: latest lineage must name a property",
                            actor, f.name
                        ));
                        stmt(ev, format!("s.{} = e.{}.clone();", f.rust, snake_field(p)), &mut arms);
                    }
                }
                "flag" => {
                    for (ev, _) in &f.from {
                        stmt(ev, format!("s.{} = true;", f.rust), &mut arms);
                    }
                    for (ev, _) in &f.removed_by {
                        stmt(ev, format!("s.{} = false;", f.rust), &mut arms);
                    }
                }
                "count" => {
                    for (ev, _) in &f.from {
                        stmt(ev, format!("s.{} += 1;", f.rust), &mut arms);
                    }
                }
                "set" => {
                    if f.scalar_of.is_some() {
                        for (ev, prop) in &f.from {
                            let p = snake_field(prop.as_deref().expect("scalar set lineage names a property"));
                            stmt(
                                ev,
                                format!(
                                    "if !s.{f}.contains(&e.{p}) {{ s.{f}.push(e.{p}.clone()); }}",
                                    f = f.rust,
                                    p = p
                                ),
                                &mut arms,
                            );
                        }
                        for (ev, prop) in &f.removed_by {
                            let p = snake_field(prop.as_deref().expect("scalar set removedBy names a property"));
                            stmt(ev, format!("s.{f}.retain(|v| *v != e.{p});", f = f.rust, p = p), &mut arms);
                        }
                    } else {
                        let tuple = f
                            .composite_of
                            .iter()
                            .map(|(k, _)| format!("e.{}.clone()", snake_field(k)))
                            .collect::<Vec<_>>()
                            .join(", ");
                        for (ev, _) in &f.from {
                            stmt(
                                ev,
                                format!(
                                    "let el = ({tuple}); if !s.{f}.contains(&el) {{ s.{f}.push(el); }}",
                                    f = f.rust
                                ),
                                &mut arms,
                            );
                        }
                        for (ev, _) in &f.removed_by {
                            stmt(
                                ev,
                                format!("let el = ({tuple}); s.{f}.retain(|v| *v != el);", f = f.rust),
                                &mut arms,
                            );
                        }
                    }
                }
                other => panic!("actors.yaml {}/state/{}: unknown mode '{}'", actor, f.name, other),
            }
        }

        // ── Emit the module ──
        let module = snake_type(actor);
        let struct_name = format!("{}State", actor);
        let imports = scalar_imports.iter().cloned().collect::<Vec<_>>().join(", ");
        out.push_str(&format!(
            "\n/// {actor} declared state (specs/actors.yaml#/{actor}/state) — the write-side fold the\n/// `requires` authorization reads.\npub mod {module} {{\n    use crate::generated::events::DomainEvent;\n    use crate::generated::scalars::{{{imports}}};\n\n"
        ));
        out.push_str(&format!("    #[derive(Debug, Clone, PartialEq)]\n    pub struct {} {{\n", struct_name));
        for f in &fields {
            if let Some(note) = state
                .get(f.name.as_str())
                .and_then(|d| d.get("note"))
                .and_then(|n| n.as_str())
            {
                out.push_str(&format!("        /// {}\n", note));
            }
            out.push_str(&format!("        pub {}: {},\n", f.rust, f.ty));
        }
        out.push_str("    }\n\n");
        out.push_str(&format!(
            "    /// Fold a stream (version order). `None` until a birth event establishes the state.\n    pub fn fold(events: &[DomainEvent]) -> Option<{s}> {{\n        events.iter().fold(None, apply)\n    }}\n\n    /// Apply one event — a pure transition, total over the whole event union.\n    pub fn apply(state: Option<{s}>, event: &DomainEvent) -> Option<{s}> {{\n        match event {{\n",
            s = struct_name
        ));
        for (ev, stmts) in &arms {
            if birth_events.contains(ev) {
                // Birth: construct fresh (replace semantics), latest fields from the payload,
                // everything else at its default. Non-latest statements for the same event
                // (a birth that also feeds a flag/set/count lineage) re-run over the fresh state.
                let mut ctor = Vec::new();
                for f in &fields {
                    if f.mode == "latest" {
                        if let Some((_, Some(p))) = f.from.iter().find(|(e, _)| e == ev) {
                            ctor.push(format!("{}: e.{}.clone()", f.rust, snake_field(p)));
                            continue;
                        }
                    }
                    ctor.push(format!("{}: Default::default()", f.rust));
                }
                // The grouped `latest` assignments are already the constructor — keep the rest.
                let extra: Vec<&String> =
                    stmts.iter().filter(|s| !(s.starts_with("s.") && s.contains(" = e."))).collect();
                out.push_str(&format!(
                    "            DomainEvent::{ev}(e) => {{\n                #[allow(unused_mut)]\n                let mut s = {s} {{ {c} }};\n",
                    s = struct_name,
                    c = ctor.join(", ")
                ));
                for st in extra {
                    out.push_str(&format!("                {}\n", st));
                }
                out.push_str("                Some(s)\n            }\n");
            } else {
                let binding = if stmts.iter().any(|s| s.contains("e.")) { "e" } else { "_" };
                out.push_str(&format!(
                    "            DomainEvent::{ev}({binding}) => {{\n                let mut s = state?;\n"
                ));
                for st in stmts {
                    out.push_str(&format!("                {}\n", st));
                }
                out.push_str("                Some(s)\n            }\n");
            }
        }
        out.push_str("            _ => state,\n        }\n    }\n}\n");
    }
    out
}

// ─── crates/domain/src/generated/answers.rs (actor answers Request/Reply, PROP-20260815-142349) ──

/// One reply/params field, resolved for emission: the Rust field, its rendered type, and the doc.
struct AnswerField {
    rust: String,
    ty: String,
    optional: bool,
    doc: Option<String>,
}

/// One declared answer operation, resolved for emission (shared between the domain types emitter
/// and the client-surface emitter so the two can never disagree).
pub(crate) struct AnswerOp {
    pub(crate) actor: String,
    pub(crate) op: String,
    /// `OrderPaymentReference` — the `<Actor><Op>` prefix of the generated Request/Reply pair.
    pub(crate) pair: String,
    /// The snake-case Rust field of the REQUEST that carries the actor's identity (the stream
    /// key — how the local adapter addresses the stream).
    pub(crate) identity_rust: String,
    /// `(reply rust field, actor-state rust field)` pairs — the projection sites.
    pub(crate) projections: Vec<(String, String)>,
}

/// Render a scalars.yaml/entities.yaml `$ref` into a Rust type name, recording the import.
fn answer_type(
    r: &str,
    scalar_imports: &mut BTreeSet<String>,
    entity_imports: &mut BTreeSet<String>,
) -> String {
    let name = ref_name(r).unwrap_or_else(|| panic!("answers: malformed type ref '{r}'"));
    match ref_target_file(r, "actors.yaml").as_deref() {
        Some("entities.yaml") => entity_imports.insert(name.clone()),
        _ => scalar_imports.insert(name.clone()),
    };
    name
}

/// The scalar `$ref` typing an actor's IDENTITY field. The identity is the stream key — it exists
/// before any fold, so it usually has NO `state:` entry of its own (see
/// `is_implicit_identity_state_ref`): its scalar is recovered from the actor's own inbox, where
/// every received message that carries a payload property named after the identity types it —
/// the same place command addressing reads it from. All carriers must AGREE (one name = one
/// dedicated scalar); a conflict or an inbox that never carries the identity returns `None` and
/// generation refuses loudly rather than guessing.
fn identity_scalar_ref(model: &Model, def: &Value, identity: &str) -> Option<String> {
    let mut found: Option<String> = None;
    let receives = def.get("receives").and_then(|r| r.as_sequence())?;
    for entry in receives {
        let Some(mref) = entry.get("message").and_then(|m| m.get("$ref")).and_then(|r| r.as_str())
        else {
            continue;
        };
        let Some((file, key)) = mref.split_once("#/") else { continue };
        let ty = model
            .defs
            .get(file)
            .and_then(|d| d.get(key))
            .and_then(|n| n.get("properties"))
            .and_then(|p| p.get(identity))
            .and_then(|f| f.get("$ref"))
            .and_then(|r| r.as_str());
        if let Some(t) = ty {
            match &found {
                None => found = Some(t.to_string()),
                Some(prev) if prev != t => return None, // conflicting carriers — refuse to guess
                _ => {}
            }
        }
    }
    found
}

/// Every declared answer operation with its resolved fields, in catalog order. Panics (loudly, at
/// generation) on shapes the `ans-*` validator already refuses — the two must agree.
fn parse_answers(model: &Model) -> Vec<(AnswerOp, Vec<AnswerField>, Vec<AnswerField>, String)> {
    let mut out = Vec::new();
    let Some(Value::Mapping(actors)) = model.defs.get("actors.yaml") else { return out };
    for (k, def) in actors {
        let Some(actor) = k.as_str().filter(|s| *s != "principals") else { continue };
        let Some(answers) = def.get("answers").and_then(|a| a.as_mapping()) else { continue };
        let identity = actor_identity_field(def, actor).unwrap_or_else(|| {
            panic!("actors.yaml {}: `answers:` needs a typed `identity` (the ask is addressed by it)", actor)
        });
        for (ok, op_def) in answers {
            let Some(op) = ok.as_str() else { continue };
            let description = op_def
                .get("description")
                .and_then(|d| d.as_str())
                .unwrap_or("")
                .trim()
                .to_string();
            let mut scalar_imports = BTreeSet::new(); // rendered per-field; imports merged later
            let mut entity_imports = BTreeSet::new();
            // The field type of one same-actor state field (reply property / identity), via the
            // shared validator resolution so generation cannot drift from `ans-reply-ref`.
            let state_field_ty = |field: &str| -> (String, bool) {
                match resolve_reply_field(def, actor, field) {
                    Some(ReplyField::Declared { flag: true, .. }) => ("bool".into(), false),
                    Some(ReplyField::Declared { type_ref: Some(r), nullable, .. }) => {
                        (ref_name(&r).expect("state type ref"), nullable)
                    }
                    Some(ReplyField::Declared { type_ref: None, .. }) => ("bool".into(), false),
                    Some(ReplyField::LifecycleStatus { status_ref }) => {
                        (ref_name(&status_ref).expect("lifecycle status ref"), false)
                    }
                    Some(ReplyField::Identity) => {
                        let r = identity_scalar_ref(model, def, field).unwrap_or_else(|| panic!(
                            "actors.yaml {}/answers/{}: the identity field '{}' has no single agreed scalar on the actor's received payloads — declare it in `state:` or fix the carriers",
                            actor, op, field
                        ));
                        (ref_name(&r).expect("identity scalar ref"), false)
                    }
                    None => panic!(
                        "actors.yaml {}/answers/{}: field '{}' must be a declared `state:` entry (or the lifecycle status / identity) so its scalar is knowable — declare it",
                        actor, op, field
                    ),
                }
            };
            // REQUEST fields: the declared params; the identity field is added when absent
            // (identity IS the argument — PROP §3's common case).
            let mut request: Vec<AnswerField> = Vec::new();
            let mut has_identity = false;
            if let Some(params) = op_def.get("params").and_then(|p| p.as_mapping()) {
                for (pk, pv) in params {
                    let pname = pk.as_str().expect("param name");
                    let r = pv.get("$ref").and_then(|x| x.as_str()).unwrap_or_else(|| {
                        panic!("actors.yaml {}/answers/{}/params/{}: params are $refs (ans-inline-type)", actor, op, pname)
                    });
                    if pname == identity {
                        has_identity = true;
                    }
                    request.push(AnswerField {
                        rust: snake_field(pname),
                        ty: answer_type(r, &mut scalar_imports, &mut entity_imports),
                        optional: false,
                        doc: None,
                    });
                }
            }
            if !has_identity {
                let (ty, _) = state_field_ty(&identity);
                request.insert(
                    0,
                    AnswerField {
                        rust: snake_field(&identity),
                        ty,
                        optional: false,
                        doc: Some(format!(
                            "The answering instance — the `{}-{{id}}` stream key IS the argument (no declared param restates it).",
                            actor
                        )),
                    },
                );
            }
            // REPLY fields: same-actor state composition.
            let mut reply: Vec<AnswerField> = Vec::new();
            let mut projections: Vec<(String, String)> = Vec::new();
            for (rk, rv) in op_def.get("reply").and_then(|r| r.as_mapping()).into_iter().flatten() {
                let rname = rk.as_str().expect("reply property name");
                let field = rv
                    .get("$ref")
                    .and_then(|x| x.as_str())
                    .and_then(parse_ref)
                    .filter(|pr| pr.path.len() == 3)
                    .map(|pr| pr.path[2].clone())
                    .unwrap_or_else(|| panic!("actors.yaml {}/answers/{}/reply/{}: reply properties are same-actor state $refs", actor, op, rname));
                let (ty, optional) = state_field_ty(&field);
                let doc = def
                    .get("state")
                    .and_then(|s| s.get(field.as_str()))
                    .and_then(|f| f.get("note"))
                    .and_then(|n| n.as_str())
                    .map(str::to_string);
                reply.push(AnswerField { rust: snake_field(rname), ty, optional, doc });
                projections.push((snake_field(rname), snake_field(&field)));
            }
            // Merge the imports into the field types (rendered names only — the emitter builds
            // one import line per file from the union below).
            let _ = (&scalar_imports, &entity_imports);
            out.push((
                AnswerOp {
                    actor: actor.to_string(),
                    op: op.to_string(),
                    pair: format!("{}{}", actor, pascal(op)),
                    identity_rust: snake_field(&identity),
                    projections,
                },
                request,
                reply,
                description,
            ));
        }
    }
    out
}

/// The declared answer operations, resolved — the client-surface emitter's view.
pub(crate) fn answer_ops(model: &Model) -> Vec<AnswerOp> {
    parse_answers(model).into_iter().map(|(op, _, _, _)| op).collect()
}

/// Emit `crates/domain/src/generated/answers.rs` — the `<Actor><Op>Request`/`<Actor><Op>Reply`
/// pair for every declared answer operation (PROP-20260815-142349 §2, #582), with UNCONDITIONAL
/// serde (the wire shape may not rot while the ask is local) and a TOLERANT reader (no
/// `deny_unknown_fields`; nullable fields are `Option` + `serde(default)`, so an absent value
/// round-trips as absent — additive-only producer / tolerant reader is the reply's whole
/// evolution contract, and a breaking reshape takes a NEW answer name).
pub(crate) fn emit_domain_answers(model: &Model) -> String {
    let mut out = String::from(
        "// GENERATED by the Captain.Food codegen from specs/actors.yaml `answers:` blocks\n// (PROP-20260815-142349 §2, #582) — do not edit by hand. The typed Request/Reply pair per\n// declared answer operation. A reply is a SNAPSHOT whose authority expires at send: never\n// stored, never folded, never api-exposed (`ans-ref-isolation`); the served stream version\n// rides the `AskOutcome` ENVELOPE (actor_client::ask), never a payload field. Serde is\n// UNCONDITIONAL and the reader TOLERANT (unknown fields are ignored, never refused):\n// additive-only producer / tolerant reader — a breaking reshape takes a NEW answer name\n// (review-carried V7). Round-trip tests live beside the hand folds\n// (crates/domain/src/{order,payment}.rs), built from real fold() fixtures so they cannot be\n// vacuous.\n",
    );
    let ops = parse_answers(model);
    if ops.is_empty() {
        return out;
    }
    // One import line over the union of every field type (bool is primitive; the rest scalars —
    // entity-typed params would import from entities the same way).
    let mut scalar_imports: BTreeSet<String> = BTreeSet::new();
    let mut entity_imports: BTreeSet<String> = BTreeSet::new();
    for (op, request, reply, _) in &ops {
        let _ = op;
        for f in request.iter().chain(reply.iter()) {
            if f.ty != "bool" {
                // Re-derive the import bucket from the model: scalars vs entities is decided by
                // where the name is declared.
                if model.defs.get("entities.yaml").map(|e| e.get(f.ty.as_str()).is_some()).unwrap_or(false) {
                    entity_imports.insert(f.ty.clone());
                } else {
                    scalar_imports.insert(f.ty.clone());
                }
            }
        }
    }
    out.push_str("\nuse serde::{Deserialize, Serialize};\n");
    if !scalar_imports.is_empty() {
        out.push_str(&format!(
            "use crate::generated::scalars::{{{}}};\n",
            scalar_imports.iter().cloned().collect::<Vec<_>>().join(", ")
        ));
    }
    if !entity_imports.is_empty() {
        out.push_str(&format!(
            "use crate::generated::entities::{{{}}};\n",
            entity_imports.iter().cloned().collect::<Vec<_>>().join(", ")
        ));
    }
    let emit_struct = |out: &mut String, name: &str, doc: &str, fields: &[AnswerField]| {
        out.push_str(&format!("\n/// {}\n", doc));
        out.push_str("#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]\n#[serde(rename_all = \"camelCase\")]\npub struct ");
        out.push_str(name);
        out.push_str(" {\n");
        for f in fields {
            if let Some(d) = &f.doc {
                out.push_str(&format!("    /// {}\n", d));
            }
            if f.optional {
                out.push_str("    #[serde(default, skip_serializing_if = \"Option::is_none\")]\n");
                out.push_str(&format!("    pub {}: Option<{}>,\n", f.rust, f.ty));
            } else {
                out.push_str(&format!("    pub {}: {},\n", f.rust, f.ty));
            }
        }
        out.push_str("}\n");
    };
    for (op, request, reply, description) in &ops {
        emit_struct(
            &mut out,
            &format!("{}Request", op.pair),
            &format!(
                "Ask `{}.{}` (actors.yaml#/{}/answers/{}): {}",
                op.actor, op.op, op.actor, op.op, description
            ),
            request,
        );
        emit_struct(
            &mut out,
            &format!("{}Reply", op.pair),
            &format!(
                "Reply of `{}.{}` — every property composes `#/{}/state/…` (declared once, served many).",
                op.actor, op.op, op.actor
            ),
            reply,
        );
    }
    out
}

