/// A scalar's `description` as `///` doc lines (one per non-empty source line, trimmed).
pub(crate) fn scalar_doc(node: &Value) -> String {
    let mut out = String::new();
    if let Some(d) = node.get("description").and_then(|d| d.as_str()) {
        for line in d.trim().lines() {
            let line = line.trim();
            if !line.is_empty() {
                out.push_str("/// ");
                out.push_str(line);
                out.push('\n');
            }
        }
    }
    out
}

/// Emit ONE scalar definition (enum or newtype) — the per-item body shared by the per-scope crate
/// emitter (`emit_domain_scope_crates`), which owns where each item now lives (#373).
pub(crate) fn push_scalar(out: &mut String, name: &str, node: &Value) {
    out.push('\n');
    out.push_str(&scalar_doc(node));
    if let Some(vals) = node.get("enum").and_then(|e| e.as_sequence()) {
        out.push_str("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]\n");
        out.push_str("#[allow(non_camel_case_types)]\n");
        out.push_str(&format!("pub enum {} {{\n", name));
        for v in vals {
            if let Some(vs) = v.as_str() {
                // Verbatim: the Rust variant IS the spec value — 1:1 spec↔code↔wire, no serde
                // transform. The value must be a valid Rust identifier; a spec smell (hyphen,
                // space, leading digit) fails here so it is fixed at the root, not masked.
                assert!(
                    vs.chars().next().map_or(false, |c| c.is_ascii_alphabetic() || c == '_')
                        && vs.chars().all(|c| c.is_ascii_alphanumeric() || c == '_'),
                    "scalars.yaml#/{}: enum value '{}' is not a valid Rust identifier — rename it in the spec",
                    name,
                    vs
                );
                out.push_str(&format!("    {},\n", vs));
            }
        }
        out.push_str("}\n");
        return;
    }
    let ty = node.get("type").and_then(|t| t.as_str()).unwrap_or("string");
    let is_uuid = node.get("format").and_then(|f| f.as_str()) == Some("uuid");
    let (derives, inner) = if is_uuid {
        ("Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize", "uuid::Uuid")
    } else if ty == "integer" {
        ("Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize", "i64")
    } else if ty == "number" {
        ("Debug, Clone, Copy, PartialEq, PartialOrd, Serialize, Deserialize", "f64")
    } else {
        // Default: a projection folding a legacy event that predates a required property
        // falls back to the empty value instead of panicking the worker (see the
        // ScalarLatest required-on-creation arm of the projector emitter).
        ("Debug, Clone, Default, PartialEq, Eq, Hash, Serialize, Deserialize", "String")
    };
    out.push_str(&format!("#[derive({})]\n", derives));
    out.push_str(&format!("pub struct {}(pub {});\n", name, inner));
}

/// The scopes that own ≥1 emitted item of `kind`, in scope order — the facade's re-export list.
fn scopes_with(model: &Model, kind: &str) -> Vec<String> {
    model
        .scopes
        .iter()
        .filter(|s| !scope_items(model, s, kind).is_empty())
        .cloned()
        .collect()
}

/// The facade banner + one `pub use domain_{scope}::{module}::*;` line per owning scope: since
/// #373 the items live in the per-scope crates (`crates/domains/{scope}`), and `crates/domain`
/// re-exports them so every `domain::generated::*` path keeps resolving with the SAME type
/// identity (a re-export is the type, not a copy).
fn facade_reexports(model: &Model, kind: &str, module: &str, what: &str) -> String {
    let mut out = format!(
        "// GENERATED by the Captain.Food codegen — do not edit by hand (#373, ADR-20260807-183024\n// step 2). {what} now live in the per-scope domain crates (specs/{{scope}}/{kind} →\n// crates/domains/{{scope}}); this facade re-exports every scope's module so existing\n// `domain::generated::{module}::*` paths keep resolving with the SAME type identity.\n",
    );
    out.push('\n');
    for s in scopes_with(model, kind) {
        out.push_str(&format!("pub use {}::{}::*;\n", domain_crate_ident(&s), module));
    }
    out
}

